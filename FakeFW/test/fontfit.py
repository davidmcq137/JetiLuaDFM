#!/usr/bin/env python3
"""Fit FontDump outputs and write FakeFW/fonts.lua (font tables per profile).

usage: python3 -I FakeFW/test/fontfit.py   (from Apps)

Model, which reproduces every measured width: each ASCII glyph has a whole
native pixel advance; getTextWidth = floor(sum of advances / scale), capped
(the emulator 6.06 stops at 150). The scale is found by search: the one at
which every repeated-character width (R lines) and single width (W lines)
is consistent. The degree sign, used in many apps, is solved from the "°"
and "°C" strings (it comes out unique on both devices). Other non-ASCII
glyphs aren't measured one by one; FakeFW uses the width of "o".
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DUMPS = {  # profile -> dump file
    "emu-ds24ii-606": "fontdump-emu606.txt",
    "ds24-508": "fontdump-ds24-508.txt",
}


def load(p):
    H, W, R, S = {}, {}, {}, []
    global LAT
    LAT = {}
    for raw in open(p, "rb"):
        l = raw.rstrip(b"\n").decode("utf-8", errors="surrogateescape")
        q = l.split(",")
        if q[0] == "L":
            LAT[q[1]] = [tuple(map(int, x.split("/"))) for x in q[2:]]
        if q[0] == "H":
            H[q[1]] = int(q[2])
        elif q[0] == "W":
            W[q[1]] = [int(x) for x in q[2:]]
        elif q[0] == "R":
            R[q[1]] = [tuple(map(int, x.split("/"))) for x in q[2:]]
        elif q[0] == "S":
            _, f, w, s = l.split(",", 3)
            S.append((f, int(w), s))
    return H, W, R, S


def natives(W, R, k):
    nat, good = {}, 0
    for f in R:
        nat[f] = []
        for i, (n, w) in enumerate(R[f]):
            c = [a for a in range(0, 100)
                 if math.floor(n * a / k + 1e-9) == w and math.floor(a / k + 1e-9) == W[f][i]]
            good += bool(c)
            nat[f].append(c[0] if c else None)
    return good, nat


def fit(p):
    H, W, R, S = load(p)
    cap = max(w for _, w, _ in S)
    capped = sum(1 for _, w, _ in S if w == cap) > 3   # many strings at the same max
    ascii_ = [(f, w, s) for f, w, s in S if all(32 <= ord(c) < 127 for c in s)]

    def misses(k, nat):
        bad = []
        for f, w, s in ascii_:
            pred = math.floor(sum(nat[f][ord(c) - 32] for c in s) / k + 1e-9)
            if capped:
                pred = min(pred, cap)
            if pred != w:
                bad.append((f, s, w, pred))
        return bad

    # among the scales where every glyph is consistent, the one that also
    # matches the most test strings
    best = None
    for i in range(1000, 2001):
        k = i / 1000
        good, nat = natives(W, R, k)
        if good != 95 * len(R):
            continue
        bad = misses(k, nat)
        if best is None or len(bad) < len(best[2]):
            best = (k, nat, bad)
    assert best, p
    k, nat, bad = best
    assert not bad, (p, k, bad)
    # Latin-1 (FontDump 1.2+): native widths from single and repeated widths
    lat = {}
    for f, items in LAT.items():
        lat[f] = []
        for w1, n, w in items:
            c = [a for a in range(0, 100)
                 if math.floor(n * a / k + 1e-9) == w and math.floor(a / k + 1e-9) == w1]
            assert c, (p, f, "latin", w1, n, w)
            lat[f].append(c[0])
    # a lone byte that isn't valid UTF-8 (sensor units' 0xB0): how is
    # "23\xB0C" measured? "stop" = up to the bad byte (emulator 6.06),
    # "latin1" = as the Latin-1 glyph
    bad = None
    for f, w, s in S:
        if f == "FONT_NORMAL" and s == "23\udcb0C":
            w23 = math.floor((nat[f][ord("2") - 32] + nat[f][ord("3") - 32]) / k + 1e-9)
            bad = "stop" if w == w23 else "latin1"
    # the degree sign: the native width that gives both "°" and "°C"
    deg = {}
    for f in W:
        d1 = [w for ff, w, s in S if ff == f and s == "\u00b0"][0]
        dc = [w for ff, w, s in S if ff == f and s == "\u00b0C"][0]
        c = nat[f][ord("C") - 32]
        cands = [a for a in range(0, 100)
                 if math.floor(a / k + 1e-9) == d1 and math.floor((a + c) / k + 1e-9) == dc]
        assert len(cands) == 1, (p, f, "degree", cands)
        deg[f] = cands[0]
    if lat:
        for f in lat:
            assert lat[f][0xB0 - 0xA0] == deg[f], (p, f, "degree", lat[f][0xB0 - 0xA0], deg[f])
    return {"scale": k, "cap": cap if capped else None, "h": H, "w": nat, "deg": deg,
            "lat": lat, "bad": bad}


def main():
    out = ["-- generated by FakeFW/test/fontfit.py from the FontDump outputs in",
           "-- FakeFW/test; do not edit. Per profile: scale, cap (nil = none),",
           "-- h[font name] = getTextHeight, w[font name] = native advance of",
           "-- ASCII 32..126, deg[font name] = the degree sign's advance,",
           "-- lat[font name] = advances of U+00A0..U+00FF (when measured),",
           "-- badByte = how a byte that isn't valid UTF-8 is measured",
           "-- (\"stop\": the width up to it; nil: not measured);",
           "-- getTextWidth = floor(sum / scale), then the cap",
           "return {"]
    for prof, fn in DUMPS.items():
        t = fit(os.path.join(HERE, fn))
        out.append('   ["%s"] = {scale = %s, cap = %s,' % (prof, t["scale"], t["cap"] or "nil"))
        out.append("      h = {" + ", ".join("%s = %d" % kv for kv in t["h"].items()) + "},")
        out.append("      deg = {" + ", ".join("%s = %d" % kv for kv in t["deg"].items()) + "},")
        out.append("      badByte = %s," % ('"%s"' % t["bad"] if t["bad"] else "nil"))
        if t["lat"]:
            out.append("      lat = {")
            for f, ws in t["lat"].items():
                out.append("         %s = {%s}," % (f, ",".join(str(x) for x in ws)))
            out.append("      },")
        out.append("      w = {")
        for f, ws in t["w"].items():
            out.append("         %s = {%s}," % (f, ",".join(str(x) for x in ws)))
        out.append("      },")
        out.append("   },")
        print(prof, "scale", t["scale"], "cap", t["cap"])
    out.append("}")
    with open(os.path.join(HERE, "..", "fonts.lua"), "w") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
